# ---- synthetic archives ----------------------------------------------------

def make_3mf(settings: dict, *, filaments=1, volume_type=0, model_settings: str | None = None,
             objects=("Thing",), header="; generated by OrcaSlicer 2.4.0-dev on x\n; total layer number: 9\n") -> bytes:
    fil_xml = "".join(
        f'<filament id="{i}" type="PLA" color="#fff" used_m="1" used_g="{i}.0"/>' for i in range(1, filaments + 1))
    obj_xml = "".join(f'<object identify_id="{i}" name="{n}" skipped="false"/>' for i, n in enumerate(objects))
    slice_info = (f'<config><plate><metadata key="index" value="1"/>'
                  f'<metadata key="nozzle_volume_type" value="{volume_type}"/>'
                  f'<metadata key="prediction" value="60"/><metadata key="weight" value="2"/>'
                  f'{obj_xml}{fil_xml}</plate></config>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("Metadata/slice_info.config", slice_info)
        z.writestr("Metadata/project_settings.config", json.dumps(settings))
        z.writestr("Metadata/plate_1.gcode", header)
        if model_settings:
            z.writestr("Metadata/model_settings.config", model_settings)
    return buf.getvalue()


BASE = {
    "printer_extruder_variant": ["Direct Drive Standard", "Direct Drive High Flow"],
    "filament_settings_id": ["A", "B"],
    "filament_self_index": ["1", "2", "2"],
    "filament_extruder_variant": ["Direct Drive Standard", "Direct Drive Standard", "Direct Drive High Flow"],
    "curr_bed_type": "Textured PEI Plate",
    "textured_plate_temp": ["55", "60"],
}


@pytest.mark.parametrize("volume_type, expected", [(0, 100), (1, 300)])
def test_variant_array_picks_active_variant(volume_type, expected):
    # Filament 2 has two entries (Standard=200, High Flow=300); filament 1 has one (100).
    s = {**BASE, "filament_max_volumetric_speed": ["100", "200", "300"]}
    info = threemf.parse(make_3mf(s, filaments=1, volume_type=volume_type))
    # primary is slot 1 (only used filament) -> 100 regardless of variant
    assert info.max_volumetric_speed == 100
    info = threemf.parse(make_3mf(s, filaments=2, volume_type=volume_type))
    # slot 2 is heaviest -> its entry for the active variant
    assert info.max_volumetric_speed == (200 if volume_type == 0 else 300)


def test_nil_means_unset_and_falls_back_to_printer_level():
    s = {**BASE, "filament_retraction_length": ["nil", "nil", "nil"], "retraction_length": ["0.8", "1.2"]}
    assert threemf.parse(make_3mf(s)).retraction == 0.8
    assert threemf.parse(make_3mf(s, volume_type=1)).retraction == 1.2
    s["filament_retraction_length"] = ["0.5", "nil", "nil"]
    assert threemf.parse(make_3mf(s)).retraction == 0.5  # filament override wins


def test_per_object_override_applies_only_when_all_objects_agree():
    ms = ('<config>'
          '<object id="1"><metadata key="name" value="A"/><metadata key="wall_loops" value="4"/></object>'
          '<object id="2"><metadata key="name" value="B"/><metadata key="wall_loops" value="4"/></object>'
          '</config>')
    s = {**BASE, "wall_loops": "2"}
    agree = threemf.parse(make_3mf(s, model_settings=ms, objects=("A", "B")))
    assert agree.walls == 4
    assert agree.object_overrides == {"A": {"wall_loops": "4"}, "B": {"wall_loops": "4"}}

    one_only = threemf.parse(make_3mf(s, model_settings=ms, objects=("A", "C")))
    assert one_only.walls == 2  # C has no override -> global stays the headline value
    assert one_only.object_overrides["A"] == {"wall_loops": "4"}


def test_gcode_header_only_is_read():
    # A header-sized read must not choke on a huge/binary-ish gcode member.
    big = "; generated by OrcaSlicer 2.4.0-dev on x\n; total layer number: 7\n" + "G1 X1\n" * 2_000_000
    info = threemf.parse(make_3mf(dict(BASE), header=big))
    assert info.layers == 7


def test_unsliced_project_is_rejected():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        z.writestr("3D/3dmodel.model", "<model/>")
    with pytest.raises(threemf.ThreeMFError):
        threemf.parse(buf.getvalue())


