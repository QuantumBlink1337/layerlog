def test_multicolor_assembly():
    info = threemf.parse(str(FIXTURES / "assembly_petg_multicolor.3mf"))
    assert (info.slicer, info.slicer_version) == ("OrcaSlicer", "2.4.0-dev")
    assert info.plate_index == 1 and info.plate_name == "Plate 1"
    assert info.process_preset == "0.16mm High Quality @BBL P2S"
    assert info.variant == "Direct Drive Standard"
    assert [f.type for f in info.filaments] == ["PETG", "PETG", "PLA"]
    assert info.primary.slot == 1 and info.primary.used_g == 24.87
    assert info.primary.preset == "SUNLU PETG @System"
    assert info.nozzle_mm == 0.4
    assert info.layer_height == 0.16 and info.first_layer_height == 0.2
    assert info.nozzle_temp == 245
    # SuperTack bed temp for filament 1, not the generic hot_plate_temp (60).
    assert info.plate_type == "SuperTack Plate" and info.bed_temp == 70
    assert info.flow_ratio == 0.95 and info.max_volumetric_speed == 14
    # filament_* is 'nil' here, so retraction/z-hop/wipe come from the printer level.
    assert (info.retraction, info.z_hop, info.wipe) == (0.8, 0.4, True)
    assert info.pressure_advance is None  # enable_pressure_advance = 0
    assert info.supports is False and info.brim == "auto_brim"
    assert (info.walls, info.infill) == (2, "15%")
    assert info.est_time_s == 8161 and info.weight_g == 40.77
    assert (info.layers, info.max_z) == (14, 2.28)
    assert info.warnings == ["bed_temperature_too_high_than_filament"]
    assert info.object_names == ["Assembly"]
    assert info.thumbnail and info.thumbnail.startswith(b"\x89PNG")


